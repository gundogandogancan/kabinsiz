"""Fit the height + weight → girth drawing estimate (ADR-011) on ANSUR II and write it as Swift.

Offline tool. Input: the public ANSUR II working databases (US Army NSRDEC 2012, "cleared for
UNLIMITED PUBLIC RELEASE", memorandum 14 April 2017), downloaded to vendor/ansur2/ from
https://tools.openlab.psu.edu/publicData/. Only stature, weight and four girths/breadths are read;
race, ethnicity, birthplace and every other demographic column are ignored.

Model, per sex (the memorandum asks that the two databases are analysed separately):
    ln(girth) = a + b·ln(weight kg) + c·ln(stature cm)
Least squares; residual SD reported. The neutral template uses the mean of the two predictions in
log space (an average of two models, not a pooled sample).

Usage (repo root):
    vendor/.venv-anny/bin/python -I scripts/avatar/fit_ansur_estimate.py \
        --ansur vendor/ansur2 --out Packages/KabinsizCore/Sources/BodyGeometry/AnthropometricEstimate.swift
"""
from __future__ import annotations

import argparse
import csv
import hashlib
from pathlib import Path

import numpy as np

# App measure ← ANSUR column (mm). Waist is ANSUR's omphalion waist; the app's tape is the natural
# waist, so the estimate is a drawing start, not a measurement.
COLUMNS = {
    "shoulderWidth": "biacromialbreadth",
    "chest": "chestcircumference",
    "waist": "waistcircumference",
    "hip": "buttockcircumference",
}


def load(path: Path):
    with path.open(newline="", encoding="latin-1") as f:
        rows = list(csv.DictReader(f))
    w = np.array([float(r["weightkg"]) / 10 for r in rows])  # kg × 10 in the file
    h = np.array([float(r["stature"]) / 10 for r in rows])  # mm → cm
    g = {k: np.array([float(r[c]) / 10 for r in rows]) for k, c in COLUMNS.items()}
    return w, h, g


def fit(w, h, y):
    X = np.stack([np.ones_like(w), np.log(w), np.log(h)], axis=1)
    coef, *_ = np.linalg.lstsq(X, np.log(y), rcond=None)
    pred = X @ coef
    resid_cm = y - np.exp(pred)
    return coef, float(np.std(np.log(y) - pred)), resid_cm


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ansur", type=Path, default=Path("vendor/ansur2"))
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    models, notes = {}, []
    for sex, name in (("female", "ANSUR_II_FEMALE_Public.csv"), ("male", "ANSUR_II_MALE_Public.csv")):
        path = args.ansur / name
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        w, h, g = load(path)
        bmi = w / (h / 100) ** 2
        notes.append(f"{name}: n={len(w)}, sha256 {digest}, BMI {np.percentile(bmi, 1):.1f}–{np.percentile(bmi, 99):.1f} (1st–99th pct)")
        models[sex] = {}
        print(f"== {sex}: n={len(w)}  BMI p1–p99 {np.percentile(bmi, 1):.1f}–{np.percentile(bmi, 99):.1f}")
        for k in COLUMNS:
            coef, sd, resid = fit(w, h, g[k])
            models[sex][k] = coef
            by_bin = []
            for lo, hi in ((15, 20), (20, 25), (25, 30), (30, 35), (35, 50)):
                m = (bmi >= lo) & (bmi < hi)
                if m.sum() >= 20:
                    by_bin.append(f"BMI {lo}-{hi}: n={m.sum()} bias {resid[m].mean():+.1f} cm")
            print(f"  {k:13s} a={coef[0]:+.4f} b(weight)={coef[1]:.4f} c(height)={coef[2]:+.4f}  "
                  f"log-SD {sd:.3f} (≈ ±{sd * 100:.0f}%)  | " + "; ".join(by_bin))
            notes.append(f"{sex} {k}: log residual SD {sd:.3f}")

    def literal(c):
        return f"(a: {c[0]:.6f}, b: {c[1]:.6f}, c: {c[2]:.6f})"

    lines = [
        "// Generated by scripts/avatar/fit_ansur_estimate.py — do not edit by hand (ADR-011).",
        "//",
        "// Source: ANSUR II working databases (US Army NSRDEC, 2012), cleared for unlimited public",
        "// release (memorandum for record, 14 April 2017). Only stature, weight and four girths were used.",
    ] + [f"// {n}" for n in notes] + [
        "",
        "/// ln(cm) = a + b·ln(weight kg) + c·ln(height cm), per sex, fitted on ANSUR II.",
        "enum AnthropometricEstimate {",
        "    typealias Coefficients = (a: Double, b: Double, c: Double)",
        "",
    ]
    for sex in ("female", "male"):
        lines.append(f"    static let {sex}: [BodyParameter: Coefficients] = [")
        for k in COLUMNS:
            lines.append(f"        .{k}: {literal(models[sex][k])},")
        lines.append("    ]")
    lines.append("}")
    args.out.write_text("\n".join(lines) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
